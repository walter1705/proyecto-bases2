BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE auditoria_tarifa CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE auditoria_tarifa (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarifa NUMBER NOT NULL,
    usuario_bd VARCHAR2(128) NOT NULL,
    fecha_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    operacion VARCHAR2(10) NOT NULL,
    valor_anterior NUMBER(12,2),
    valor_nuevo NUMBER(12,2)
);

CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
FOR INSERT OR UPDATE OR DELETE ON tarifa
COMPOUND TRIGGER
    TYPE t_evento IS RECORD (
        id_tarifa tarifa.id_tarifa%TYPE,
        operacion VARCHAR2(10),
        anterior tarifa.valor_noche%TYPE,
        nuevo tarifa.valor_noche%TYPE
    );
    TYPE t_eventos IS TABLE OF t_evento INDEX BY PLS_INTEGER;
    g_eventos t_eventos;
    g_indice PLS_INTEGER := 0;

    AFTER EACH ROW IS
    BEGIN
        g_indice := g_indice + 1;
        IF INSERTING THEN
            g_eventos(g_indice).id_tarifa := :NEW.id_tarifa;
            g_eventos(g_indice).operacion := 'INSERT';
            g_eventos(g_indice).anterior := NULL;
            g_eventos(g_indice).nuevo := :NEW.valor_noche;
        ELSIF UPDATING THEN
            g_eventos(g_indice).id_tarifa := :NEW.id_tarifa;
            g_eventos(g_indice).operacion := 'UPDATE';
            g_eventos(g_indice).anterior := :OLD.valor_noche;
            g_eventos(g_indice).nuevo := :NEW.valor_noche;
        ELSE
            g_eventos(g_indice).id_tarifa := :OLD.id_tarifa;
            g_eventos(g_indice).operacion := 'DELETE';
            g_eventos(g_indice).anterior := :OLD.valor_noche;
            g_eventos(g_indice).nuevo := NULL;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. g_indice LOOP
            INSERT INTO auditoria_tarifa (
                id_tarifa, usuario_bd, operacion, valor_anterior, valor_nuevo
            ) VALUES (
                g_eventos(i).id_tarifa, SYS_CONTEXT('USERENV', 'SESSION_USER'),
                g_eventos(i).operacion, g_eventos(i).anterior, g_eventos(i).nuevo
            );
        END LOOP;
    END AFTER STATEMENT;
END;
/

CREATE OR REPLACE TRIGGER trg_control_solapamiento_rh
FOR INSERT OR UPDATE OF id_habitacion, fecha_checkin, fecha_checkout ON reserva_habitacion
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF reserva_habitacion.id_reserva%TYPE INDEX BY PLS_INTEGER;
    g_ids t_ids;
    g_indice PLS_INTEGER := 0;

    AFTER EACH ROW IS
    BEGIN
        g_indice := g_indice + 1;
        g_ids(g_indice) := :NEW.id_reserva;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        l_conflictos NUMBER;
    BEGIN
        FOR i IN 1 .. g_indice LOOP
            SELECT COUNT(*)
            INTO l_conflictos
            FROM reserva_habitacion a
            JOIN reserva ra ON ra.id_reserva = a.id_reserva
            JOIN reserva_habitacion b ON b.id_habitacion = a.id_habitacion
            JOIN reserva rb ON rb.id_reserva = b.id_reserva
            WHERE a.id_reserva = g_ids(i)
              AND ra.estado IN ('CONFIRMADA', 'FINALIZADA')
              AND b.id_reserva <> a.id_reserva
              AND rb.estado IN ('CONFIRMADA', 'FINALIZADA')
              AND a.fecha_checkin < b.fecha_checkout
              AND a.fecha_checkout > b.fecha_checkin;
            IF l_conflictos > 0 THEN
                raise_application_error(-20007,
                    'La reserva genera solapamiento de habitaciones.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END;
/

CREATE OR REPLACE TRIGGER trg_control_solapamiento_estado
AFTER UPDATE OF estado ON reserva
FOR EACH ROW
WHEN (NEW.estado = 'CONFIRMADA' OR NEW.estado = 'FINALIZADA')
DECLARE
    l_conflictos NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO l_conflictos
    FROM reserva_habitacion a
    JOIN reserva_habitacion b ON b.id_habitacion = a.id_habitacion
    JOIN reserva rb ON rb.id_reserva = b.id_reserva
    WHERE a.id_reserva = :NEW.id_reserva
      AND b.id_reserva <> a.id_reserva
      AND rb.estado IN ('CONFIRMADA', 'FINALIZADA')
      AND a.fecha_checkin < b.fecha_checkout
      AND a.fecha_checkout > b.fecha_checkin;
    IF l_conflictos > 0 THEN
        raise_application_error(-20008,
            'El cambio de estado genera un solapamiento.');
    END IF;
END;
/
